const fs = require('fs');
const path = require('path');
const { execSync } = require('child_process');

const rootDir = path.resolve(__dirname, '..');
const versionJsonPath = path.join(rootDir, 'version.json');
const versionJsPath = path.join(rootDir, 'version.js');
const assetsVersionJsPath = path.join(rootDir, 'assets', 'version.js');
const packageJsonPath = path.join(rootDir, 'package.json');

// 1. Determine Git metadata if available
let commitCount = 68;
let commitHash = 'b7396fb';
let hasGit = false;

try {
  const countStr = execSync('git rev-list --count HEAD', { cwd: rootDir, encoding: 'utf8' }).trim();
  const hashStr = execSync('git rev-parse --short HEAD', { cwd: rootDir, encoding: 'utf8' }).trim();
  if (countStr && !isNaN(parseInt(countStr, 10))) {
    commitCount = parseInt(countStr, 10);
    commitHash = hashStr;
    hasGit = true;
  }
} catch (e) {
  // Fallback to reading existing version.json
}

// 2. Read or initialize version.json
let currentData = {
  major: 2,
  minor: 4,
  patch: commitCount,
  version: `2.4.${commitCount}`,
  channel: 'production'
};

if (fs.existsSync(versionJsonPath)) {
  try {
    currentData = JSON.parse(fs.readFileSync(versionJsonPath, 'utf8'));
  } catch (err) {
    console.warn('Could not parse version.json, creating anew.');
  }
}

const major = currentData.major || 2;
const minor = currentData.minor || 4;

// If in git, patch is sync'd to commit count; otherwise increment
let patch = hasGit ? commitCount : (parseInt(currentData.patch || 0, 10) + 1);

const fullVersion = `${major}.${minor}.${patch}`;
const now = new Date();
const dateStr = now.toISOString().split('T')[0];

const updatedVersionData = {
  version: fullVersion,
  major: major,
  minor: minor,
  patch: patch,
  commit: commitHash,
  commitCount: commitCount,
  releaseName: 'Bharat Retail Intelligence',
  updatedAt: now.toISOString(),
  releaseDate: dateStr,
  channel: currentData.channel || 'production'
};

// 3. Save version.json
fs.writeFileSync(versionJsonPath, JSON.stringify(updatedVersionData, null, 2) + '\n', 'utf8');

